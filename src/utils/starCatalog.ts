/** 디코딩된 항성 배열. 위치는 적도좌표(J2000)입니다. */
export interface DecodedStars {
  /** 적경 (시간, 0~24) */
  raHours: Float32Array;
  /** 적위 (도, -90~+90) */
  decDeg: Float32Array;
  /** 겉보기 등급 (낮을수록 밝음) */
  magnitude: Float32Array;
  /** B-V 색지수 (낮을수록 푸른 별) */
  colorIndex: Float32Array;
  count: number;
}

function base64ToBytes(b64: string): Uint8Array {
  // atob은 RN Hermes에도 있지만, 없을 경우를 대비해 수동 디코더를 둡니다.
  const table = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/';
  const clean = b64.replace(/=+$/, '');
  const out = new Uint8Array((clean.length * 3) >> 2);
  let acc = 0;
  let bits = 0;
  let o = 0;
  for (let i = 0; i < clean.length; i++) {
    acc = (acc << 6) | table.indexOf(clean[i]);
    bits += 6;
    if (bits >= 8) {
      bits -= 8;
      out[o++] = (acc >> bits) & 0xff;
    }
  }
  return out;
}

let cache: DecodedStars | null = null;

/**
 * 항성 카탈로그를 디코딩합니다. 결과는 캐시되므로 여러 번 불러도 안전합니다.
 */
export function getStarCatalog(): DecodedStars {
  if (cache) return cache;

  const bytes = base64ToBytes(PACKED);
  const count = Math.floor(bytes.length / 6);

  const raHours = new Float32Array(count);
  const decDeg = new Float32Array(count);
  const magnitude = new Float32Array(count);
  const colorIndex = new Float32Array(count);

  for (let i = 0; i < count; i++) {
    const o = i * 6;
    const ra = bytes[o] | (bytes[o + 1] << 8);
    let dec = bytes[o + 2] | (bytes[o + 3] << 8);
    if (dec > 32767) dec -= 65536; // int16 부호 복원
    raHours[i] = (ra / 65535) * 24;
    decDeg[i] = (dec / 32767) * 90;
    magnitude[i] = bytes[o + 4] / 28 - 2;
    colorIndex[i] = bytes[o + 5] / 56 - 0.5;
  }

  cache = { raHours, decDeg, magnitude, colorIndex, count };
  return cache;
}

/**
 * B-V 색지수 → 선형 RGB.
 *
 * 뜨거운 별(B-V가 낮음)은 푸르고, 차가운 별은 붉습니다. 실제 흑체 색온도
 * 근사이며, 화면에서 별이 전부 흰 점으로 보이지 않게 해줍니다.
 * 다만 눈으로 보는 별은 어두워서 채도가 낮게 느껴지므로 살짝 눌러둡니다.
 */
export function bvToLinearRGB(bv: number): [number, number, number] {
  // 1) Ballesteros(2012) 근사로 B-V에서 유효 색온도를 얻습니다.
  const kelvin = 4600 * (1 / (0.92 * bv + 1.7) + 1 / (0.92 * bv + 0.62));

  // 2) 흑체 색온도 → sRGB (Tanner Helland 근사).
  //    이 근사는 온도를 **100으로 나눈** 값을 기준으로 하며, 분기점도 66(=6600K)
  //    입니다. 1000으로 나누면 모든 별이 회색에 가까워집니다.
  const t = Math.max(1000, Math.min(40000, kelvin)) / 100;

  let r: number;
  let g: number;
  let b: number;
  if (t <= 66) {
    r = 1.0;
    g = 0.390081579 * Math.log(t) - 0.631841444;
  } else {
    r = 1.292936186 * Math.pow(t - 60, -0.1332047592);
    g = 1.129890861 * Math.pow(t - 60, -0.0755148492);
  }
  if (t >= 66) b = 1.0;
  else if (t <= 19) b = 0.0;
  else b = 0.543206789 * Math.log(t - 10) - 1.196254089;

  r = Math.max(0, Math.min(1, r));
  g = Math.max(0, Math.min(1, g));
  b = Math.max(0, Math.min(1, b));

  // 3) sRGB → 선형. 셰이더는 선형 값을 더하므로 이 변환을 빠뜨리면
  //    색 차이가 감마에 눌려 전부 흰 점처럼 보입니다.
  const lin = (c: number) => (c <= 0.04045 ? c / 12.92 : Math.pow((c + 0.055) / 1.055, 2.4));
  let lr = lin(r);
  let lg = lin(g);
  let lb = lin(b);

  // 4) 육안으로 보는 별은 어두워서 색이 이 정도로 진하게 느껴지지는 않습니다.
  //    다만 완전히 눌러버리면 전부 백색 점이 되므로 살짝만 뺍니다.
  const desat = 0.78;
  const lum = 0.2126 * lr + 0.7152 * lg + 0.0722 * lb;
  lr = lum + (lr - lum) * desat;
  lg = lum + (lg - lum) * desat;
  lb = lum + (lb - lum) * desat;

  // 5) 가장 밝은 채널을 1로 맞춰 색만 남기고 밝기는 등급이 결정하게 합니다.
  const peak = Math.max(lr, lg, lb, 1e-6);
  return [lr / peak, lg / peak, lb / peak];
}
