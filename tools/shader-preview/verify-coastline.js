/**
 * **해안선이 마스크가 아니라 기하인가** 합격 판정 (docs/COASTLINE_PLAN.md 4단계).
 *
 * 땅(`TerrainField`)과 물(`SeaPlane`)을 각각 진짜 면으로 두면 해안선은 **두 면의
 * 교선**입니다. 따로 그리지 않아도 만·곶·섬이 제 모양으로 나오고, 방위 해상도
 * 12° 라는 한계 자체가 사라집니다.
 *
 * ## 재는 법
 *
 * 땅을 빨강, 물을 파랑으로 칠해 30° 씩 12방향으로 한 바퀴를 찍고, **화소마다**
 * 종류를 CPU 광선행진 결과와 견줍니다:
 *
 *     바다각(d) = atan2(0 − 눈높이 − d²/2R, d)        ← 어디에나 있음
 *     지면각(d) = atan2(고도(d) − 눈높이 − d²/2R, d)  ← 격자 안에만
 *     보이는각(d) = max(둘),  종류 = 큰 쪽
 *     d 를 키우며 보이는각이 지금까지의 최대를 넘을 때만 보입니다
 *
 * 이 행진은 **가림까지** 포함합니다 — 3km 앞 능선이 6km 뒤 바다를 가리는 것이
 * 저절로 나옵니다.
 *
 * ⚠ 관측점은 1·2단계와 **다릅니다.** 같은 점(37.25, 126.58)을 쓰면 고도 42m 에
 * 사방이 더 높아 **어느 방위로도 물이 안 보이고**, 그러면 물을 대상이 없습니다.
 * DEM 을 훑어 고도 1~30m 이면서 바다와 뭍이 같이 보이는 점을 골랐습니다.
 *
 * ## 대조
 *
 * ① **수평선 (손으로 푼 답).** 맨 위에 있는 것이 물인 방위에서는 그 위를
 *    가리는 것이 없으므로 물이 수평선까지 이어집니다. 그 각은 정확히
 *    `−acos(R/(R+눈높이))` 여야 합니다.
 * ② **한 광선의 다중 전환.** 섬·만이 있으면 한 광선에서 땅↔물이 여러 번
 *    바뀝니다. 방위마다 값 하나를 갖는 마스크로는 못 만드는 구조입니다.
 * ③ **하늘 일치.** 참조가 말하는 실루엣 위쪽이 실제로 비어 있는가.
 *
 * ## 이 판정이 잡은 결함 셋
 *
 * **1. 발밑 각도 구멍 (지면 격자가 12m 부터 시작).** 눈높이 2.77m 에서 12m 앞
 * 지면은 −6.3° 이고 그보다 아래는 지면이 **아예 없었습니다.** 더 낮은 각까지
 * 뻗는 해수면이 그 구멍을 메워서, 물가에 선 관측자가 발밑에 물을 밟고 선 것처럼
 * 그려졌습니다. 격자를 0.6m 부터 시작하는 두 구간(발밑 24고리 + 바깥 128고리)
 * 으로 바꿨습니다. ⚠ 발밑 고리를 바깥에서 빼내면 안 됩니다 — 그러면 먼 쪽
 * 실루엣이 나빠집니다 (2단계 최대오차 0.119° → 0.161°).
 *
 * **2. 먼바다가 통째로 뭍으로 그려짐.** Terrarium 은 **먼바다를 정확히 0 으로
 * 자릅니다** (조사 때 표본 1024개 중 406개가 정확히 0). 그러면 지면 메시가
 * 해수면과 똑같은 높이에 면을 깔고, 깊이 동률에서 지면이 이깁니다. 해수면 아래
 * (`vElevM <= 0`)를 그리지 않도록 고쳤습니다 — 거기서 보이는 것은 땅이 아니라
 * 물입니다.
 *
 *     고치기 전:  맨 위 물 평균 −0.481° (이론 −0.053°) · 화소일치 —
 *     고친 뒤:    맨 위 물 평균 −0.089° · 화소일치 99.24%
 *
 * **3. 판정 자신의 결함.** 참조의 "하늘 시작점"으로 경계 목록의 마지막 항목을
 * 썼는데, 그건 마지막 **종류 변화**이지 맨 위가 아닙니다. 하늘 일치율이 0.77 로
 * 나왔고 렌더가 아니라 측정이 틀린 것이었습니다. 맨 위를 따로 넘겨 0.99999.
 *
 * ## 전환 수를 문턱으로 쓰지 않는 이유
 *
 * 참조는 고리 표본 사이의 **화소보다 얇은** 조각까지 셉니다 (참조 11회 대 측정
 * 4회). 읽기 해상도가 0.0586°/행 인데 못 그리는 것을 세는 것은 불공정합니다.
 * 그래서 문턱은 **화소 단위 일치율**로 잡고, 전환은 "그런 구조가 실제로
 * 나오는가"(다중 전환 열 수)로만 씁니다.
 *
 * 준비:
 *   node tools/shader-preview/build-coastline.js
 *   node tools/shader-preview/stage-esm.js
 * 사용: node tools/shader-preview/verify-coastline.js
 */
const { chromium } = require('/opt/node22/lib/node_modules/playwright');
const { ORIGIN } = require('./paths');

let pass = 0;
let fail = 0;
function ok(cond, label) {
  if (cond) { pass++; console.log('  PASS: ' + label); }
  else { fail++; console.log('  FAIL: ' + label); }
}

(async () => {
  const b = await chromium.launch({
    executablePath: '/opt/pw-browsers/chromium',
    args: ['--no-sandbox', '--use-gl=swiftshader', '--enable-unsafe-swiftshader'],
  });
  const p = await b.newPage({ viewport: { width: 1220, height: 900 } });
  const pageErrors = [];
  p.on('pageerror', e => pageErrors.push(e.message));
  await p.goto(ORIGIN + '/coastline.html', { timeout: 180000 });
  await p.waitForFunction(() => /^DONE::/.test(document.title), null,
    { timeout: 180000, polling: 500 }).catch(() => {});

  const title = await p.title();
  const stats = await p.evaluate(() => window.__stats || null);
  const errs = await p.evaluate(() => window.__errors || []);
  await b.close();

  console.log('== 셰이더 · GL ==');
  ok(pageErrors.length === 0,
    `페이지 오류 없음 ${pageErrors.length ? '— ' + pageErrors[0] : ''}`);
  ok(!/ERR/.test(title), `셰이더 컴파일 (${title})`);
  ok(errs.length === 0, `콘솔 오류 없음 (${errs.length}건)`);
  if (!stats || !stats.결과) {
    console.log('\nFAILURES — __stats.결과 가 없습니다.');
    process.exit(1);
  }
  ok(stats.glError === 0, `glGetError == 0 (${stats.glError})`);

  const r = stats.결과;

  console.log('\n== 화소마다 땅/물이 맞는가 ==');
  console.log(`  지면 화소 ${r.화소맞음 + r.화소틀림} · 맞음 ${r.화소맞음} · 틀림 ${r.화소틀림}`);
  console.log(`  일치율 ${(r.화소일치율 * 100).toFixed(2)}%`);
  // 어긋나는 것은 경계 화소뿐이어야 합니다 (반올림 반 칸).
  ok(r.화소일치율 >= 0.98,
    `땅/물 경계가 자료가 말하는 자리 (${(r.화소일치율 * 100).toFixed(2)}% ≥ 98%)`);
  ok(r.미분류 === 0,
    `모든 지면 화소가 땅 아니면 물로 분류됨 (미분류 ${r.미분류})`);

  console.log('\n== 대조 ③ 실루엣 위는 하늘인가 ==');
  console.log(`  하늘 화소 ${r.하늘맞음 + r.하늘틀림} · 틀림 ${r.하늘틀림}`);
  ok(r.하늘일치율 >= 0.999,
    `참조 실루엣 위가 비어 있음 (${(r.하늘일치율 * 100).toFixed(3)}% ≥ 99.9%)`);

  console.log('\n== 맨 위 경계 ==');
  console.log(`  물 맨위: 중앙 ${r.바다맨위중앙}° · 최대 ${r.바다맨위최대}°`);
  console.log(`  땅 맨위: 중앙 ${r.땅맨위중앙}° · 최대 ${r.땅맨위최대}°`);
  // 읽기 해상도가 행당 0.0586° 입니다.
  ok(r.바다맨위중앙 <= 0.06, `물 맨위가 화소 한 칸 안 (${r.바다맨위중앙}° ≤ 0.06°)`);
  ok(r.땅맨위중앙 <= 0.06, `땅 맨위가 화소 한 칸 안 (${r.땅맨위중앙}° ≤ 0.06°)`);
  ok(r.바다맨위최대 <= 0.6, `물 맨위 최대오차 (${r.바다맨위최대}° ≤ 0.6°)`);
  ok(r.땅맨위최대 <= 0.3, `땅 맨위 최대오차 (${r.땅맨위최대}° ≤ 0.3°)`);

  console.log('\n== 대조 ① 수평선 (손으로 푼 답) ==');
  console.log(`  맨 위가 물인 열 ${r.열린바다열} · 그 각 평균 ${r.열린바다맨위}° (폭 ${r.열린바다폭}°)`);
  console.log(`  이론 ${r.수평선이론}° · 수평선 거리 ${r.수평선거리km}km`);
  ok(r.열린바다열 >= 50, `수평선이 보이는 방위가 충분 (${r.열린바다열}열)`);
  ok(Math.abs(r.열린바다맨위 - r.수평선이론) <= 0.06,
    `물이 진짜 수평선까지 이어짐 (${r.열린바다맨위}° 대 ${r.수평선이론}°, 화소 한 칸)`);
  ok(r.열린바다폭 <= 0.15, `수평선이 방위에 안 흔들림 (폭 ${r.열린바다폭}°)`);

  console.log('\n== 대조 ② 마스크로는 못 만드는 구조 ==');
  console.log(`  한 광선에서 2회 이상 땅↔물을 오가는 열: 참조 ${r.참조.다중전환열} · 측정 ${r.다중전환열}`);
  console.log(`  전환 수가 방위를 따라 바뀌는 횟수 ${r.참조.전환변화}회 (열 간격 0.234°)`);
  ok(r.다중전환열 >= 300,
    `섬·만이 실제로 나옴 — 한 광선에 여러 번 (${r.다중전환열}열)`);
  ok(Math.abs(r.다중전환열 - r.참조.다중전환열) <= r.참조.다중전환열 * 0.05,
    `그 구조가 자료와 일치 (측정 ${r.다중전환열} 대 참조 ${r.참조.다중전환열})`);
  // 12° 마스크라면 한 바퀴에 30칸뿐이라 이만큼 못 바뀝니다.
  ok(r.참조.전환변화 >= 60,
    `해안 구조가 12° 보다 훨씬 잘게 바뀜 (${r.참조.전환변화}회 ≥ 60)`);

  console.log(`\n${fail ? 'FAILURES' : '모두 통과'} — pass ${pass} / fail ${fail}`);
  process.exit(fail ? 1 : 0);
})();
