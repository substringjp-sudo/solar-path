/**
 * 오존 Chappuis 흡수의 **채널별 유효 광학두께**를 밴드 적분으로 구합니다.
 *
 * 지금 코드는 650/550/450nm 한 점씩만 샘플합니다. 그런데 Chappuis 대역의
 * 정점은 602nm — sRGB **적색 채널 한가운데**입니다. 650nm는 정점에서
 * 이미 내려온 자락이라, 한 점 샘플링은 적색 흡수를 크게 과소평가합니다.
 * 그 결과 녹색만 깎이고 적색·청색이 남아 **자홍색**이 만들어집니다.
 *
 * 여기서는 σ(λ)를 CIE 등색함수(Wyman et al. 2013 해석적 근사)와
 * sRGB 변환에 걸어 적분해, 채널이 실제로 느끼는 유효 τ를 구합니다.
 */

// O3 Chappuis 흡수단면적 (10^-21 cm^2/molecule, 293K), 10nm 간격
const SIGMA = {
  400:0.005,410:0.012,420:0.028,430:0.055,440:0.10,450:0.17,460:0.28,470:0.43,
  480:0.63,490:0.92,500:1.28,510:1.62,520:2.01,530:2.35,540:2.75,550:3.10,
  560:3.62,570:4.05,580:4.36,590:4.62,600:4.85,610:4.72,620:4.48,630:3.92,
  640:3.35,650:2.75,660:2.30,670:1.90,680:1.55,690:1.28,700:1.05,710:0.88,
  720:0.75,730:0.62,740:0.53,750:0.45,
};

// 조각별 가우시안 (Wyman, Sloan & Shirley 2013)
const pg = (x, mu, s1, s2) => {
  const t = (x - mu) * (x < mu ? 1 / s1 : 1 / s2);
  return Math.exp(-0.5 * t * t);
};
const xbar = l => 1.056 * pg(l, 599.8, 37.9, 31.0) + 0.362 * pg(l, 442.0, 16.0, 26.7) - 0.065 * pg(l, 501.1, 20.4, 26.2);
const ybar = l => 0.821 * pg(l, 568.8, 46.9, 40.5) + 0.286 * pg(l, 530.9, 16.3, 31.1);
const zbar = l => 1.217 * pg(l, 437.0, 11.8, 36.0) + 0.681 * pg(l, 459.0, 26.0, 13.8);

const XYZ2RGB = [
  [ 3.2406, -1.5372, -0.4986],
  [-0.9689,  1.8758,  0.0415],
  [ 0.0557, -0.2040,  1.0570],
];

// D65 근사 (CIE D65 상대 분광분포, 10nm — 형태만 맞으면 충분)
const D65 = {
  400:82.8,410:91.5,420:93.4,430:86.7,440:104.9,450:117.0,460:117.8,470:114.9,
  480:115.9,490:108.8,500:109.4,510:107.8,520:104.8,530:107.7,540:104.4,550:104.0,
  560:100.0,570:96.3,580:95.8,590:88.7,600:90.0,610:89.6,620:87.7,630:83.3,
  640:83.7,650:80.0,660:80.2,670:82.3,680:78.3,690:69.7,700:71.6,710:74.3,
  720:61.6,730:69.9,740:75.1,750:63.6,
};

const LAMS = Object.keys(SIGMA).map(Number).sort((a, b) => a - b);
// 300 DU 연직 기둥의 분자수 (molecules/cm^2)
const N_300DU = 8.07e18;

/** 오존 slant 배수 m 에서 채널별 유효 투과율 → τ_eff */
function effectiveTau(m) {
  const acc = [0, 0, 0], ref = [0, 0, 0];
  for (const l of LAMS) {
    const w = D65[l];
    const cmf = [xbar(l), ybar(l), zbar(l)];
    const T = Math.exp(-SIGMA[l] * 1e-21 * N_300DU * m);
    for (let i = 0; i < 3; i++) { acc[i] += w * T * cmf[i]; ref[i] += w * cmf[i]; }
  }
  const toRGB = v => XYZ2RGB.map(row => row[0] * v[0] + row[1] * v[1] + row[2] * v[2]);
  const a = toRGB(acc), r = toRGB(ref);
  const Tc = [0, 1, 2].map(i => Math.max(1e-6, a[i] / r[i]));
  return { T: Tc, tau: Tc.map(t => -Math.log(t) / m) };
}

console.log('slant m │ 유효 투과율 R/G/B        │ 유효 τ (연직 300DU 환산) R/G/B');
console.log('────────┼──────────────────────────┼────────────────────────────────');
for (const m of [1, 2, 5, 10, 20, 30, 38, 50]) {
  const e = effectiveTau(m);
  console.log(
    String(m).padStart(7) + ' │ ' +
    e.T.map(v => v.toFixed(4)).join('  ').padEnd(24) + ' │ ' +
    e.tau.map(v => v.toFixed(4)).join('  ')
  );
}

