/**
 * **물가를 거리장으로 다시 세우면 경계가 덜 각지는가** 합격 판정.
 * `bake-shore-sdf.js` → `build-shore-sdf.js` 의 짝.
 *
 * ## 먼저: 자가 너무 얇았습니다
 *
 * 예전 자(`build-shorepatch.js`)는 줄마다 "뭍에서 물로 넘어가는 **첫** 자리"
 * 하나만 적었습니다. 384줄 중 **29~37줄**만 쓰였고, 그 표본으로는 1.4 와
 * 2.5 를 못 가립니다 — 실제로 격자 밀도를 바꾸면 값이 오르락내리락 해서
 * 아무 결론도 못 냈습니다. 못 박아 둔 **2.286** 도 그 얇은 자의 값이고,
 * 두꺼운 자로 같은 화면을 다시 재면 **1.634** 였습니다 (겹침 전 값입니다 —
 * 지금은 1.349 입니다, 10.5절).
 *
 * 이제 **모든 경계**를 적어 표본이 176~254 로 늡니다. 그러자 숫자가
 * 단조로워졌습니다.
 *
 * ## 그래서 나온 답 둘
 *
 * ① **경계는 격자가 아니라 자료가 정합니다.** 살을 늘릴수록 각짐이
 *    **커집니다**(1.349 → 1.713 → 1.714). 성긴 격자가 계단을 뭉개 주고
 *    있었을 뿐입니다. 렌더링 쪽에서 더 짜낼 것이 없다는 뜻입니다.
 *
 * ② **거리장은 각짐을 자의 바닥까지 끌어내립니다** — 기본 격자에서
 *    1.349 → 1.000, 살 4배에서 1.714 → 1.016. 두 밀도에서 **도착점이**
 *    같으니 우연이 아닙니다. 다만 그것이 전부입니다: 같은 래스터에서 만든
 *    거리장은 **텍셀 안의 정보를 지어낼 수 없고**, 양자화된 계단을 고를
 *    뿐입니다.
 *
 * ⚠ **위 숫자는 해수면 겹침이 들어온 뒤 값입니다.** 겹침 전에는
 *   1.774 → 2.057 → 2.193 / 1.568 / 1.936 이었습니다. 겹침이 기준선을
 *   내리고 해수면 격자 의존을 없앴습니다 — COASTLINE_PLAN 10.5절.
 *
 * ⚠ 거리장 타일은 고원(기울기 0)을 1:31 경사로 바꾸므로 셰이더의 `trust`
 * 판단이 달라집니다 — 포말이 8.1% → 10.7% 로 늡니다. 그러니 −12% 가 순수한
 * 경계 이득만은 아닙니다. 아래에서 그것도 못 박습니다.
 *
 * 사용: node tools/shader-preview/bake-shore-sdf.js
 *       node tools/shader-preview/build-shore-sdf.js
 *       node tools/shader-preview/verify-shore-sdf.js
 */
const { chromium } = require('/opt/node22/lib/node_modules/playwright');
const { ORIGIN } = require('./paths');

let pass = 0, fail = 0;
const ok = (c, l) => { if (c) { pass++; console.log('  PASS: ' + l); } else { fail++; console.log('  FAIL: ' + l); } };

(async () => {
  const b = await chromium.launch({
    executablePath: '/opt/pw-browsers/chromium',
    args: ['--no-sandbox', '--use-gl=swiftshader', '--enable-unsafe-swiftshader'],
  });
  const p = await b.newPage({ viewport: { width: 900, height: 700 } });
  const pageErrors = [];
  p.on('pageerror', e => pageErrors.push(e.message));
  await p.goto(ORIGIN + '/shore-sdf.html', { timeout: 300000 });
  await p.waitForFunction(() => /^DONE::/.test(document.title), null,
    { timeout: 300000, polling: 500 }).catch(() => {});
  const title = await p.title();
  const stats = await p.evaluate(() => window.__stats || null);
  const errs = await p.evaluate(() => window.__errors || []);
  await b.close();

  console.log('== 셰이더 · GL ==');
  ok(pageErrors.length === 0, `페이지 오류 없음 ${pageErrors.length ? '— ' + pageErrors[0] : ''}`);
  ok(!/ERR/.test(title), `셰이더 컴파일 (${title})`);
  ok(errs.length === 0, `콘솔 오류 없음 (${errs.length}건)`);
  if (!stats || !stats.결과) { console.log('\nFAILURES — __stats.결과 가 없습니다.'); process.exit(1); }
  ok(stats.glError === 0, `glGetError == 0 (${stats.glError})`);

  const r = stats.결과;
  console.log('\n== 대부도 갯벌 · 자료와 격자를 따로 흔들어 본 것 ==');
  for (const [k, v] of Object.entries(r))
    console.log(`  ${k.padEnd(14)} 각짐 ${String(v.경계각짐).padStart(6)}`
      + ` · 표본 ${String(v.경계줄).padStart(4)}줄`
      + ` · 뭍 ${v.뭍} · 포말 ${v.포말} (${v.포말비율}%) · 물 ${v.물}`);

  const 앱 = r['앱 그대로'];
  const 기본 = r['원본 기본'], 살2 = r['원본 살2배'], 살4 = r['원본 살4배'];
  const S기본 = r['거리장 기본'], S살4 = r['거리장 살4배'];
  const 흐림 = r['고도흐림 기본'];
  const 겹0앱 = r['겹침0 앱'], 겹0기본 = r['겹침0 기본'];

  console.log('\n== 자가 결론을 낼 만큼 두꺼운가 ==');
  //
  // ⚠ 이게 먼저입니다. 예전 자는 29~37줄이었고 그 표본으로 낸 결론이
  //   격자 밀도에 따라 뒤집혔습니다. 얇아지면 여기서 걸립니다.
  ok(Object.values(r).every(v => v.경계줄 >= 150),
    `모든 경우에서 표본이 150줄 이상 (${Object.values(r).map(v => v.경계줄).join(' · ')})`);

  console.log('\n== 두 자가 서로를 확인하는가 ==');
  //
  // '앱 그대로' 는 해수면을 기본값(96 고리)으로 둔, 곧 앱과 같은 설정입니다.
  // 이 값이 verify-shorepatch 의 것과 같아야 두 하네스가 같은 것을 재고
  // 있다고 말할 수 있습니다. 아래 A/B 들은 해수면도 지형과 같은 밀도로
  // 맞춘 설정입니다 — 겹침이 들어온 지금은 둘이 같은 값을 냅니다(아래).
  // ⚠ **절대 상수를 박으면 안 됩니다.** 처음에 1.634 를 박았는데 지형 음영이
  //   바뀔 때마다(①② 법선·결) 밀렸고, 그 뒤로도 실행마다 1.827 ↔ 1.716 으로
  //   흔들렸습니다 — 갈래를 색으로 나누는 자라 SwiftShader 편차를 그대로
  //   받습니다. 상수를 계속 따라 고치는 것은 골대를 옮기는 것과 같습니다.
  //
  //   대신 **같은 실행 안의 관계**를 봅니다. 처음엔 "'앱 그대로'(해수면 96
  //   고리)가 '원본 기본'(152 고리)보다 성기니 각짐이 낮아야 한다" 로 짰는데,
  //   **해수면 한쪽 겹침(uShoreOverlapM)이 들어오면서 그 전제가 없어졌습니다.**
  //
  //   겹침 전에는 경계가 지형면과 해수면의 **교선**이었습니다. 둘이 같은 0
  //   등고선을 각자 다른 표본으로 계산하니, 해수면 격자를 촘촘히 하면 교선이
  //   달라졌습니다. 겹침을 주면 해수면이 지형 가장자리 **밑으로 늘 이기므로**
  //   보이는 경계는 지형의 discard 가장자리 하나입니다 — 해수면 밀도는 이제
  //   경계에 아무 영향이 없습니다.
  //
  //   논증이 아니라 **재서** 못 박습니다. 같은 두 칸을 겹침만 0 으로 둔
  //   대조에서는 밀도 의존이 그대로 돌아옵니다:
  //
  //     겹침 3m : 앱 1.349 = 기본 1.349   (밀도 무관)
  //     겹침 0  : 앱 1.716 < 기본 1.851   (옛 전제 그대로 살아 있음)
  //
  //   그리고 겹침은 각짐 자체도 줄입니다 (1.716 → 1.349, −21%).
  ok(Math.abs(앱.경계각짐 - 기본.경계각짐) <= 0.05,
    `겹침이 있으면 해수면 격자 밀도가 경계를 안 바꾼다 — 경계는 지형 가장자리다`
    + ` (앱 ${앱.경계각짐} = 기본 ${기본.경계각짐})`);
  // ⚠ 위가 "자가 눈멀어서" 같아 보이는 것일 수도 있습니다. 겹침을 끄면
  //   같은 자가 밀도 차이를 도로 봅니다 — 그래야 위 등호가 뜻이 있습니다.
  ok(겹0앱.경계각짐 < 겹0기본.경계각짐,
    `대조: 겹침을 끄면 밀도 의존이 돌아온다 — 자가 눈먼 것이 아니다`
    + ` (${겹0앱.경계각짐} < ${겹0기본.경계각짐})`);
  ok(앱.경계각짐 < 겹0앱.경계각짐,
    `그리고 겹침이 각짐을 줄인다`
    + ` (${겹0앱.경계각짐} → ${앱.경계각짐},`
    + ` ${(100 * (겹0앱.경계각짐 - 앱.경계각짐) / 겹0앱.경계각짐).toFixed(1)}%)`);
  ok(앱.경계각짐 > 1.0 && 앱.경계각짐 < 2.4,
    `그리고 값이 터무니없지 않다 (${앱.경계각짐}, 1.0~2.4)`);

  console.log('\n== ① 경계는 격자가 아니라 자료가 정한다 ==');
  ok(살2.경계각짐 > 기본.경계각짐 && 살4.경계각짐 > 살2.경계각짐,
    `살을 늘릴수록 각짐이 커진다 — 성긴 격자가 계단을 뭉개고 있었다`
    + ` (${기본.경계각짐} → ${살2.경계각짐} → ${살4.경계각짐})`);
  ok(살4.살 === 4 * 기본.살, `살을 실제로 네 배로 늘렸다 (${기본.살} → ${살4.살})`);

  console.log('\n== ② 거리장은 같은 격자에서 각짐을 줄인다 ==');
  // ⚠ **자가 바닥에 닿았습니다.** 각짐은 경계 x 좌표의 2차 차분을 **화소
  //   단위**로 평균한 값이라, 줄마다 ±1화소씩 떠는 경계가 곧 1.0 입니다 —
  //   그 아래로는 못 내려갑니다. 열 경우 중 1.000 미만이 하나도 없습니다.
  //
  //   겹침이 기준선을 1.716 → 1.349 로 끌어내리면서 거리장 두 칸이 **바닥에
  //   붙었습니다**(1.000 · 1.016). 그래서 예전의 "두 밀도에서 이득 비율이
  //   비슷하다(±6%p)" 는 뜻을 잃었습니다 — 25.9% 대 40.7% 로 갈리는 것은
  //   거리장이 밀도마다 다르게 듣기 때문이 아니라, **기준선이 다른데 도착점이
  //   같은 바닥**이기 때문입니다. 비율을 견주는 대신 **도착점**을 봅니다.
  //
  //   ⚠ 뒤집어 말하면 이 자로는 여기서 더 잴 수 없습니다. 벡터 해안선의
  //     이득을 재려면 화소 아래를 보는 자가 필요합니다.
  const 이득기본 = (기본.경계각짐 - S기본.경계각짐) / 기본.경계각짐;
  const 이득살4 = (살4.경계각짐 - S살4.경계각짐) / 살4.경계각짐;
  ok(이득기본 >= 0.03,
    `기본 격자에서 ${(100 * 이득기본).toFixed(1)}% 줄었다 (${기본.경계각짐} → ${S기본.경계각짐})`);
  ok(이득살4 >= 0.03,
    `살 4배에서도 ${(100 * 이득살4).toFixed(1)}% 줄었다 (${살4.경계각짐} → ${S살4.경계각짐})`);
  ok(Math.abs(S기본.경계각짐 - S살4.경계각짐) <= 0.10,
    `두 밀도에서 거리장이 같은 자리에 데려다 놓는다 — 우연이 아니다`
    + ` (${S기본.경계각짐} · ${S살4.경계각짐})`);
  ok(Object.values(r).every(v => v.경계각짐 >= 1.0),
    `자의 바닥은 1.0 이다 — 열 경우 중 그 아래가 없다`
    + ` (가장 낮은 값 ${Math.min(...Object.values(r).map(v => v.경계각짐))})`);

  console.log('\n== 대조: 고도를 그냥 흐리면 오히려 나빠진다 ==');
  //
  // "거리장은 고도 흐리기와 다른 물건" 은 오래 논증으로만 있었습니다 — 예전에
  // 한 번 재긴 했지만 그때 자가 얇아 믿을 수 없었습니다. 같은 띠·같은 σ 로
  // 고도장을 흐린 타일을 함께 구워 재면 측정이 됩니다.
  //
  // 이유도 분명합니다: 고원 위에서 고도는 기울기가 0 이라 흐려도 여전히 0 이고
  // 등고선이 다른 모서리로 옮겨갈 뿐입니다. 거리장은 어디서나 기울기가 1 이라
  // 흐리면 양자화된 계단이 원래 곡선으로 돌아옵니다.
  ok(흐림.경계각짐 > 기본.경계각짐,
    `고도를 흐리면 각짐이 커진다 (${기본.경계각짐} → ${흐림.경계각짐})`);
  ok(S기본.경계각짐 < 기본.경계각짐 && S기본.경계각짐 < 흐림.경계각짐,
    `거리장만 줄인다 — 고도흐림 ${흐림.경계각짐} · 원본 ${기본.경계각짐}`
    + ` · 거리장 ${S기본.경계각짐}`);

  console.log('\n== 대조: 거짓으로 이긴 것이 아닌가 ==');
  //
  // 각짐만 보면 "물을 다 지우기" 가 만점을 받습니다. 해안선이 통째로
  // 옮겨가지 않았는지, 물이 사라지지 않았는지 함께 봅니다.
  ok(Math.abs(S기본.뭍 - 기본.뭍) / 기본.뭍 <= 0.02,
    `해안선을 통째로 옮기지 않았다 — 뭍 화소 ${기본.뭍} → ${S기본.뭍}`
    + ` (${(100 * Math.abs(S기본.뭍 - 기본.뭍) / 기본.뭍).toFixed(2)}%)`);
  ok(S기본.물 >= 0.8 * 기본.물,
    `물을 지워서 이긴 것이 아니다 (${기본.물} → ${S기본.물})`);

  console.log('\n== 남는 값: 거리장이 깊이 판단도 건드린다 ==');
  //
  // 고원(기울기 0)을 1:31 경사로 바꾸므로 셰이더의 trust 가 그 자리를
  // 믿기 시작합니다. 그래서 −12% 가 순수한 경계 이득만은 아닙니다.
  // 나중에 이것까지 잡으면 이 단언이 걸리고, 그때 값을 새로 못 박으면 됩니다.
  ok(S기본.포말 > 기본.포말,
    `거리장은 포말을 늘린다 — 고원에 기울기가 생겨 trust 가 달라진다`
    + ` (${기본.포말비율}% → ${S기본.포말비율}%)`);

  console.log(`\n${fail ? 'FAILURES' : '모두 통과'} — pass ${pass} / fail ${fail}`);
  process.exit(fail ? 1 : 0);
})();
